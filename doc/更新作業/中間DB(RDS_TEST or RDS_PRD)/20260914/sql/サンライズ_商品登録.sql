       2. 一時テーブル → @target_table へ INSERT ... SELECT する
          （この文だけ変数から組み立てて PREPARE / EXECUTE で実行）

     一時テーブルは接続（セッション）を切ると自動で消える。
     変数（@target_table など）も接続ごとに消えるため、接続し直した場合は
     「設定」から実行し直すこと。

   ★ id ★

     INSERT では id を指定しない（登録先の AUTO_INCREMENT で採番される）。

   進め方 : 設定 → STEP 0 → 1 → 2 → 3 → 4 → COMMIT → 5 の順に、
            各ブロックを選択して実行する。
   ============================================================================ */



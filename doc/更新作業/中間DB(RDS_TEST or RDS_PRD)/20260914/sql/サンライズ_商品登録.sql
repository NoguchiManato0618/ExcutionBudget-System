   件数   : 985 件

   ---------------------------------------------------------------------------
   ★ Excel 列 → テーブル列の対応 ★

     A メーカー名          → manufacturer
     B 品名-product_name   → product_name
     C 品番-productnumber  → productnumber   ※ Excel では色名が入力されている
     D 色-color            → color           ※ Excel では全行空欄のため NULL
     E 入数-quantity       → quantity
     F 単位-case_unit      → case_unit
     G 定尺                → length          ※ 全行空欄のため NULL
     H 価格                → standard_price  ※ 全行空欄のため 0
     （Excel に無い列）    → case, quantity_unit は NULL

   ---------------------------------------------------------------------------
   ★ 仕組み ★

     MySQL はテーブル名に変数を直接使えないため、次の手順で登録する。

       1. 登録先と同じ構成の一時テーブル `ExcutionBudget`.`tmp_import_sunrise` を作り、
